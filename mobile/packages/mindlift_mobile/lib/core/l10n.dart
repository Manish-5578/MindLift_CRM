/// Switches the app's text to [language]. Call whenever the language changes.
void applyLanguage(AppLanguage language) {
  if (language == AppLanguage.arabic) {
    MlStrings.translate = (s) => arabic[s] ?? s;
  } else {
    MlStrings.translate = (s) => s;
  }
}
